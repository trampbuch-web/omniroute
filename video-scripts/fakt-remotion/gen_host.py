# Writes src/hostMarkup.ts: Timofey's SVG (viewBox 0 0 600 900) from the studio template,
# slim build, two explicit arms (no <use>), a mug in the right hand. Run once.
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "..", "midterms-animation.html")).read()
host = re.search(r'<svg id="host" viewBox="0 0 600 900">(.*?)\n      </svg>', src, re.S).group(1)
arm = re.search(r'(<g id="arm">.*?\n          </g>)', host, re.S).group(1)
host = host.replace(arm, "")
arm = arm.replace('<rect x="-36" y="-10" width="72" height="200" rx="34" fill="url(#sleeve)" />', '<rect x="-27" y="-10" width="54" height="200" rx="26" fill="url(#sleeve)" />')
arm = arm.replace('<rect x="-30" y="-12" width="60" height="165" rx="28" fill="url(#sleeve)" />', '<rect x="-23" y="-12" width="46" height="165" rx="22" fill="url(#sleeve)" />')
arm = arm.replace('<rect x="-29" y="138" width="58" height="18" rx="6" fill="#f2f4f8" />', '<rect x="-23" y="138" width="46" height="18" rx="6" fill="#f2f4f8" />')
arm = arm.replace('<g class="hand" transform="translate(0 178)">', '''<g class="hand" transform="translate(0 178)">
                <g class="cup" opacity="0"><g class="cupR"><g transform="scale(1.45)">
                  <rect x="-24" y="-46" width="48" height="56" rx="7" fill="#f4f4f4" />
                  <rect x="-24" y="-30" width="48" height="11" fill="#e3262f" />
                  <path d="M-24 -36 Q-46 -32 -44 -18 Q-42 -6 -24 -8" stroke="#f4f4f4" stroke-width="7" fill="none" />
                </g></g></g>''', 1)
inner = re.sub(r'^<g id="arm">', "", arm.strip())[:-4]
for side, base in (("armL", "translate(158 600)"), ("armR", "translate(442 600) scale(-1 1)")):
    host = re.sub(rf'<g id="{side}"[^>]*><use href="#arm" /></g>', f'<g id="{side}" transform="{base}">{inner}</g>', host)
assert host.count('class="fore"') == 2, host.count('class="fore"')
assert host.count('<g transform="translate(0 -45)">') == 1
host = host.replace('<g transform="translate(0 -45)">', '<g transform="translate(300 0) scale(0.72 1) translate(-300 -45)">', 1)
# glasses glint the page sweeps across the lenses now and then
host = host.replace('<g id="head">', '<g id="head"><defs><linearGradient id="glint" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#fff" stop-opacity="0"/><stop offset="0.5" stop-color="#fff" stop-opacity="0.75"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></linearGradient></defs>', 1)
anchor = '<path d="M294 350 Q300 343 306 350"'
assert host.count(anchor) == 1
host = host.replace(anchor, '<clipPath id="lensClip"><rect x="198" y="326" width="96" height="68" rx="12"/><rect x="306" y="326" width="96" height="68" rx="12"/></clipPath><g clip-path="url(#lensClip)"><rect id="glint" x="-60" y="300" width="40" height="130" fill="url(#glint)" transform="skewX(-20)"/></g>' + anchor, 1)
for i in ("eyeL", "eyeR", "iris", "mouthOpen", "teeth", "lowLip", "brows", "fringe", "head", "torso"):
    assert i in host, i
open(os.path.join(HERE, "src", "hostMarkup.ts"), "w").write("// generated by gen_host.py\nexport const HOST = " + json.dumps(host, ensure_ascii=False) + ";\n")
print(len(host))
